// npm run fonts → fonts/*.woff2 + css/fonts.css  (self-hosted Nunito + DM Mono: no requests to Google, GDPR-friendly, CSP: font-src 'self')
const fs = require('fs'), path = require('path');
const R = {
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
  cyrillic: 'U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116',
  'latin-ext': 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF'
};
const FONTS = [
  { fam: 'Nunito', pkg: 'nunito', w: [500, 600, 700, 800], subs: ['latin', 'cyrillic'] },
  { fam: 'DM Mono', pkg: 'dm-mono', w: [400, 500], subs: ['latin', 'latin-ext'] }
];
fs.mkdirSync('fonts', { recursive: true });
let css = '/* Self-hosted fonts (SIL OFL 1.1) — generated by scripts/fonts.js */\n', n = 0;
for (const f of FONTS) {
  const dir = `node_modules/@fontsource/${f.pkg}/files/`;
  if (!fs.existsSync(dir)) { console.warn('skip fonts: run npm install first'); process.exit(0); }
  for (const w of f.w) for (const sub of f.subs) {
    const name = `${f.pkg}-${sub}-${w}-normal.woff2`;
    fs.copyFileSync(dir + name, 'fonts/' + name); n++;
    css += `@font-face{font-family:"${f.fam}";font-style:normal;font-weight:${w};font-display:swap;src:url("../fonts/${name}") format("woff2");unicode-range:${R[sub]}}\n`;
  }
  const lic = `node_modules/@fontsource/${f.pkg}/LICENSE`;
  if (fs.existsSync(lic)) fs.copyFileSync(lic, `fonts/LICENSE-${f.pkg}.txt`);
}
fs.writeFileSync('css/fonts.css', css);
console.log('✓ fonts:', n, 'files');
